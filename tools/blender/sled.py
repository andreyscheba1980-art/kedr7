# Генератор 3D-модели экспедиционных нарт Семёнова для игры «Кедр-7».
# Нарты перевёрнуты набок на обочине склона: кованые полозья, деревянные плахи,
# перерезанные ножом кожаные постромки собачьей упряжи, привязанный брезентовый баул
# и планшет дежурного с приколотой запиской под обледеневшей плёнкой.
# Запуск: blender --background --python sled.py -- <out_dir>
import bpy, math, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kit
from kit import box, cyl, sphere, tube, mat

OUT = sys.argv[-1] if len(sys.argv) > 1 and not sys.argv[-1].endswith(".py") else "."
os.makedirs(OUT, exist_ok=True)
kit.reset()

# Материалы советской экспедиции 80-х
WOOD = mat("sled_wood", (0.32, 0.22, 0.14), rough=0.75, wear=0.6, dirt=0.7, wear_col=(0.48, 0.38, 0.26))
WOOD_DARK = mat("sled_wood_dark", (0.22, 0.15, 0.10), rough=0.8, wear=0.4, dirt=0.8)
STEEL = mat("sled_runner", (0.16, 0.17, 0.18), rough=0.45, wear=0.8, dirt=0.5, wear_col=(0.55, 0.58, 0.60))
RUST = mat("sled_rust", (0.24, 0.12, 0.07), rough=0.85, wear=0.3, dirt=0.6)
TARP = mat("tarp_canvas", (0.28, 0.29, 0.22), rough=0.85, wear=0.5, dirt=0.65, wear_col=(0.38, 0.40, 0.32))
LEATHER = mat("harness_leather", (0.14, 0.08, 0.05), rough=0.6, wear=0.7, dirt=0.7, wear_col=(0.28, 0.18, 0.12))
PAPER = mat("report_paper", (0.82, 0.79, 0.70), rough=0.9, wear=0.2, dirt=0.35)
SNOW = mat("snow_crust", (0.88, 0.92, 0.96), rough=0.95, wear=0.0, dirt=0.0)

# Размеры нарт: длина 2.4 м, ширина 0.75 м, высота стоек 0.32 м
L, W, H = 2.4, 0.75, 0.32

# 1. ПОЛОЗЬЯ (два массивных загнутых бруса с подбитыми стальными полосами)
for sy in (-1, 1):
    y = sy * (W / 2 - 0.06)
    # Основная прямая часть деревянного полоза
    box(f"runner_wood_{sy}", (L - 0.5, 0.08, 0.07), (0.1, y, 0.035), WOOD, 0.006)
    # Стальная кованая полоса снизу
    box(f"runner_steel_{sy}", (L - 0.5, 0.082, 0.015), (0.1, y, -0.005), STEEL, 0.002)
    
    # Загнутый нос нарты (спереди, +X)
    tube(f"runner_nose_wood_{sy}", [
        (L / 2 - 0.15, y, 0.035),
        (L / 2 + 0.12, y, 0.09),
        (L / 2 + 0.28, y, 0.24),
        (L / 2 + 0.34, y, 0.42),
        (L / 2 + 0.26, y, 0.48)
    ], 0.038, WOOD, 8)
    tube(f"runner_nose_steel_{sy}", [
        (L / 2 - 0.15, y, -0.005),
        (L / 2 + 0.12, y, 0.05),
        (L / 2 + 0.28, y, 0.20),
        (L / 2 + 0.34, y, 0.38)
    ], 0.016, STEEL, 6)

# 2. ПОПЕРЕЧНЫЕ ВЯЗКИ (копылья) — вертикальные стойки и поперечные брусья
for i in range(5):
    x = -L / 2 + 0.35 + i * 0.42
    # Поперечный нижний брус
    box(f"cross_beam_{i}", (0.07, W - 0.04, 0.06), (x, 0, 0.06), WOOD_DARK, 0.004)
    # Стойки-копылья (слева и справа)
    for sy in (-1, 1):
        y = sy * (W / 2 - 0.06)
        cyl(f"post_{i}_{sy}", 0.024, H - 0.06, (x, y, H / 2 + 0.02), WOOD, verts=8)
        # Стальная скоба крепления копыла
        box(f"bracket_{i}_{sy}", (0.04, 0.05, 0.03), (x, y, 0.07), RUST, 0.002)

# 3. ВЕРХНИЕ ПРОДОЛЬНЫЕ НАПРАВЛЯЮЩИЕ И НАСТИЛ
for sy in (-1, 1):
    y = sy * (W / 2 - 0.06)
    box(f"top_rail_{sy}", (L - 0.3, 0.06, 0.05), (0.05, y, H), WOOD, 0.005)

# Продольные плахи настила грузовой площадки
num_planks = 6
plank_w = (W - 0.16) / num_planks
for p in range(num_planks):
    py = -(W - 0.16) / 2 + (p + 0.5) * plank_w
    box(f"deck_plank_{p}", (L - 0.5, plank_w - 0.012, 0.025), (0.05, py, H + 0.025), WOOD if p % 2 else WOOD_DARK, 0.003)

# 4. БРЕЗЕНТОВЫЙ ЭКСПЕДИЦИОННЫЙ БАУЛ (привязан веревками к настилу)
box("tarp_cargo", (1.2, W - 0.18, 0.36), (-0.1, 0, H + 0.22), TARP, 0.03)
box("cargo_bulge", (0.9, W - 0.24, 0.14), (-0.05, 0, H + 0.42), TARP, 0.04)

# Веревки обвязки груза (крест-накрест)
for rx in (-0.5, -0.1, 0.3):
    tube(f"cargo_rope_{rx}", [
        (rx, -(W / 2 - 0.05), H),
        (rx, -(W / 2 - 0.10), H + 0.41),
        (rx, (W / 2 - 0.10), H + 0.41),
        (rx, (W / 2 - 0.05), H)
    ], 0.010, LEATHER, 6)

# 5. ПЕРЕРЕЗАННЫЕ КОЖАНЫЕ ПОСТРОМКИ УПРЯЖИ (спереди, у загнутых носков нарт)
# Центральный тяговый ремень (потяг), перерезанный ножом под углом
tube("main_trace", [
    (L / 2 + 0.26, 0, 0.35),
    (L / 2 + 0.50, 0.05, 0.22),
    (L / 2 + 0.68, -0.04, 0.10),
    (L / 2 + 0.78, 0.08, 0.02)
], 0.016, LEATHER, 6)

# Свисающие боковые постромки с заклепками (перерезанные концы лежат на снегу)
for sy in (-1, 1):
    y = sy * 0.15
    tube(f"cut_harness_{sy}", [
        (L / 2 + 0.52, y * 0.5, 0.20),
        (L / 2 + 0.75, y * 1.4, 0.12),
        (L / 2 + 0.92, y * 2.1, 0.01),
        (L / 2 + 1.05, y * 2.4, 0.01)
    ], 0.012, LEATHER, 6)

# 6. ПЛАНШЕТ ДЕЖУРНОГО С ПРИКОЛОТОЙ ЗАПИСКОЙ
# Фанерный полевой планшет 28×20 см
box("tablet_base", (0.28, 0.20, 0.012), (0.25, 0.05, H + 0.43), WOOD_DARK, 0.002, rot=(0.08, -0.12, 0.25))
# Металлический пружинный зажим сверху
box("tablet_clip", (0.04, 0.12, 0.02), (0.37, 0.05, H + 0.44), STEEL, 0.002, rot=(0.08, -0.12, 0.25))
# Лист бумаги с неровными краями (записка Семёнова)
box("note_paper", (0.24, 0.17, 0.004), (0.24, 0.05, H + 0.44), PAPER, 0.001, rot=(0.08, -0.12, 0.25))

# 7. СНЕЖНЫЙ НАДУВ НА ОБОЧИНЕ И ПОД ПОЛОЗЬЯМИ
box("snow_drift_back", (1.4, 0.45, 0.18), (-0.4, -(W / 2 + 0.08), 0.08), SNOW, 0.05, rot=(0.05, 0.04, -0.15))
box("snow_drift_top", (0.8, 0.35, 0.08), (-0.15, 0.05, H + 0.44), SNOW, 0.03)

obj, img, tris = kit.finish("sled_semenov", OUT, res=1024, origin="center", samples=32)
kit.export(os.path.join(OUT, "sled_semenov.glb"), os.path.join(OUT, "sled_semenov.blend"))
print("[OK] Sled exported, tris:", tris)
